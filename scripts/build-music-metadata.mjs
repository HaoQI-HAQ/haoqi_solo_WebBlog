#!/usr/bin/env node
// Run after adding/editing local MP3s: node scripts/build-music-metadata.mjs
// --check verifies the checked-in snapshot without writing it. Browser builds
// consume the snapshot, so browsing albums never downloads audio for ID3 tags.
import { open, readFile, writeFile } from 'node:fs/promises';
import { dirname, isAbsolute, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { musicTracks } from '../src/content.js';
import { artworkCatalog } from '../src/work-archive/artworkCatalog.js';
import { readableTrackFilename } from '../src/work-archive/musicMetadataFallback.js';
import { id3RegionSize, parseId3Text, parseId3v1Text } from './lib/music-id3.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const publicRoot = resolve(root, 'public');
const outputPath = resolve(root, 'src/work-archive/musicMetadataCatalogData.js');
const MAX_TAG_BYTES = 32 * 1024 * 1024;
let bytesRead = 0;

function localPath(src) {
  if (!src.startsWith('/media/') || /[?#]/.test(src)) throw new Error(`Expected an unencoded local media path: ${src}`);
  const path = resolve(publicRoot, `.${src}`);
  const offset = relative(publicRoot, path);
  if (offset.startsWith('..') || isAbsolute(offset)) throw new Error(`Media path leaves public: ${src}`);
  return path;
}

async function readTags(src) {
  const file = await open(localPath(src), 'r');
  try {
    const info = await file.stat();
    const header = Buffer.alloc(10);
    bytesRead += (await file.read(header, 0, 10, 0)).bytesRead;
    const region = id3RegionSize(header);
    if (region > MAX_TAG_BYTES || region > info.size) throw new Error(`Invalid ID3 length for ${src}`);
    let metadata = {};
    if (region) {
      const tag = Buffer.alloc(region);
      header.copy(tag);
      bytesRead += (await file.read(tag, 10, region - 10, 10)).bytesRead;
      metadata = parseId3Text(tag);
    }
    if ((!metadata.title || !metadata.artist || !metadata.album) && info.size >= 128) {
      const tail = Buffer.alloc(128);
      bytesRead += (await file.read(tail, 0, 128, info.size - 128)).bytesRead;
      metadata = { ...parseId3v1Text(tail), ...metadata };
    }
    return metadata;
  } finally { await file.close(); }
}

function readable(value) {
  return typeof value === 'string' && value.trim() && !/^(READING MP3|ID3 ARCHIVE|APIC ARCHIVED|LOCAL COLLECTION)/i.test(value) ? value.trim() : '';
}

const tracks = {};
const albums = {};
for (const album of musicTracks.filter(item => !item.pending)) {
  const known = artworkCatalog[album.archiveCode]?.metadata || {};
  const trackIds = [];
  for (const track of album.tracks || []) {
    if (tracks[track.id]) throw new Error(`Duplicate track id: ${track.id}`);
    const tags = await readTags(track.src);
    const filename = readableTrackFilename(track.src);
    tracks[track.id] = {
      src: track.src,
      archiveCode: album.archiveCode,
      title: readable(tags.title) || readable(track.title) || filename.title,
      artist: readable(tags.artist) || readable(track.artist) || filename.artist || known.artist || '',
      album: readable(tags.album) || known.album || readable(album.title) || '',
      ...(tags.duration ? { duration: tags.duration } : {}),
    };
    trackIds.push(track.id);
  }
  albums[album.archiveCode] = {
    album: known.album || readable(album.title),
    artist: known.artist || tracks[trackIds[0]]?.artist || '',
    trackIds,
  };
}

const content = '// Generated by scripts/build-music-metadata.mjs from local ID3 tags. Do not edit by hand.\n'
  + '// Duration is seconds from a valid TLEN tag; absent durations are read by the audio player.\n'
  + `export const musicTrackCatalog = ${JSON.stringify(tracks, null, 2)};\n\n`
  + `export const musicAlbumCatalog = ${JSON.stringify(albums, null, 2)};\n`;
if (process.argv.includes('--check')) {
  if (await readFile(outputPath, 'utf8') !== content) throw new Error('Music metadata snapshot is stale. Run node scripts/build-music-metadata.mjs.');
} else await writeFile(outputPath, content);
console.log(`${process.argv.includes('--check') ? 'Verified' : 'Generated'} ${Object.keys(tracks).length} tracks / ${Object.keys(albums).length} albums; read ${(bytesRead / 1024 / 1024).toFixed(2)} MiB of ID3 regions.`);
